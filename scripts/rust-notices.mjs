#!/usr/bin/env node
// Keeps the "Rust crates" table of THIRD_PARTY_NOTICES.md in sync with the
// crates that ship in the desktop binary (docs/architecture.md, section 8.4),
// the table of the Rust crates in the Android app's library (D223), and the
// table of server/THIRD_PARTY_NOTICES.md with the crates of the sync server's
// binary (D225, item 14).
//
//   node scripts/rust-notices.mjs           check (default; scripts/verify.ps1,
//                                           scripts/verify-android.ps1, CI)
//   node scripts/rust-notices.mjs --write   rewrite the generated parts
//
// The desktop list is the union, over the desktop targets below, of the normal
// (non-dev, non-build) dependencies of `shellpp-desktop` (the GPUI Kit app in
// apps/desktop, default features: `dev-tools` never ships) as resolved by
// `cargo tree`; the Android list is the same for `shellpp-android`
// (apps/android/native) over the phone's and the emulator's targets, which
// both go into the APK; the server list is the same for `shellpp-server`
// (server/, a workspace of its own) over the musl targets its image builds
// for. Procedural macros run in the compiler and are not part of the binary,
// so they are left out; so are the workspace crates themselves. SQLite, which
// libsqlite3-sys bundles, is public domain and gets its own row in the "Other"
// table of each file. Licenses are checked by cargo-deny (deny.toml,
// server/deny.toml); this script only records them.

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const DESKTOP_TARGETS = [
  'x86_64-pc-windows-msvc',
  'aarch64-pc-windows-msvc',
  'x86_64-apple-darwin',
  'aarch64-apple-darwin',
  'x86_64-unknown-linux-gnu',
  'aarch64-unknown-linux-gnu',
];

const ROOT_PACKAGE = 'shellpp-desktop';
const ANDROID_TARGETS = ['aarch64-linux-android', 'x86_64-linux-android'];
const ANDROID_PACKAGE = 'shellpp-android';
const NOTICES_FILE = 'THIRD_PARTY_NOTICES.md';
// The server's image builds a static musl binary (server/Dockerfile) on the
// machine's architecture.
const SERVER_TARGETS = ['x86_64-unknown-linux-musl', 'aarch64-unknown-linux-musl'];
const SERVER_PACKAGE = 'shellpp-server';
const SERVER_MANIFEST = 'server/Cargo.toml';
const SERVER_NOTICES_FILE = 'server/THIRD_PARTY_NOTICES.md';
const RUST_START = '<!-- rust-crates:start (generated by scripts/rust-notices.mjs) -->';
const RUST_END = '<!-- rust-crates:end -->';
const ANDROID_START = '<!-- android-rust-crates:start (generated by scripts/rust-notices.mjs) -->';
const ANDROID_END = '<!-- android-rust-crates:end -->';
// The license files of the Android app's crates, shipped in the APK (its
// licenses screen; review of run 16).
const ANDROID_LICENSES_FILE = 'apps/android/app/src/main/assets/notices/rust-licenses.txt';
const SQLITE_ROW_PREFIX = '| SQLite (bundled by ';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function cargo(args) {
  return execFileSync('cargo', args, {
    cwd: repoRoot,
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
    stdio: ['ignore', 'pipe', 'inherit'],
  });
}

/** Old-style "MIT/Apache-2.0" license fields become SPDX "MIT OR Apache-2.0". */
function normalizeLicense(license) {
  return license
    .split('/')
    .map((part) => part.trim())
    .join(' OR ');
}

function compareVersions(a, b) {
  return a.localeCompare(b, 'en', { numeric: true });
}

/** The `--manifest-path` arguments of a workspace other than the root one. */
function manifestArgs(manifest) {
  return manifest === undefined ? [] : ['--manifest-path', manifest];
}

/**
 * Returns the crates `rootPackage` ships on `targets`: { name, version,
 * license, source }; `manifest` names another workspace's Cargo.toml.
 */
function collectCrates(rootPackage, targets, manifest) {
  const crates = new Map();
  for (const target of targets) {
    const output = cargo([
      'tree',
      ...manifestArgs(manifest),
      '--locked',
      '--package',
      rootPackage,
      '--target',
      target,
      '--edges',
      'normal,no-proc-macro',
      '--prefix',
      'none',
      '--format',
      '{p}\t{l}\t{r}',
    ]);
    for (const rawLine of output.split('\n')) {
      // cargo tree marks repeated subtrees with a trailing "(*)".
      const line = rawLine.replace(/\s*\(\*\)\s*$/, '').trim();
      if (line === '') {
        continue;
      }
      const [pkg, license = '', repository = ''] = line.split('\t');
      // Registry crates print "name vX.Y.Z"; path crates add " (<path>)". Path
      // crates are the workspace's own, except the patched third-party crates
      // under third_party/ (D100), which ship like registry crates.
      const match = /^(\S+) v(\S+)(?: \((.+)\))?$/.exec(pkg.trim());
      if (match === null) {
        continue;
      }
      const path = match[3];
      if (path !== undefined && !/[\\/]third_party[\\/]/.test(path)) {
        continue;
      }
      const [, name, version] = match;
      const key = `${name}@${version}`;
      if (crates.has(key)) {
        continue;
      }
      if (license.trim() === '') {
        throw new Error(`${key} declares no license expression; add it by hand after checking its license files`);
      }
      const source = repository.trim() !== '' ? repository.trim() : `https://crates.io/crates/${name}/${version}`;
      crates.set(key, { name, version, license: normalizeLicense(license.trim()), source });
    }
  }
  return [...crates.values()].sort((a, b) => a.name.localeCompare(b.name, 'en') || compareVersions(a.version, b.version));
}

/**
 * The license files (LICENSE*, LICENCE*, COPYING*, NOTICE*, UNLICENSE*) of
 * `crates`, as found in their packages: one block per distinct text with
 * the crates that ship it, so the copyright lines stay with their crates.
 */
function licenseTexts(crates) {
  const metadata = JSON.parse(cargo(['metadata', '--locked', '--format-version', '1']));
  const packages = new Map(metadata.packages.map((pkg) => [`${pkg.name}@${pkg.version}`, pkg]));
  const blocks = new Map();
  const without = [];
  for (const crate of crates) {
    const pkg = packages.get(`${crate.name}@${crate.version}`);
    if (pkg === undefined) {
      throw new Error(`${crate.name} ${crate.version} is not in cargo metadata`);
    }
    const dir = dirname(pkg.manifest_path);
    const files = readdirSync(dir)
      .filter((file) => /^(licen[cs]e|copying|notice|unlicense)/i.test(file) && statSync(join(dir, file)).isFile())
      .sort();
    if (files.length === 0) {
      without.push(`${crate.name} ${crate.version} (${crate.license})`);
      continue;
    }
    for (const file of files) {
      const text = readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trim();
      const users = blocks.get(text) ?? [];
      users.push(`${crate.name} ${crate.version} (${file})`);
      blocks.set(text, users);
    }
  }
  const out = [
    'The license files of the Rust crates in the Android app\'s library',
    '(libshellpp_android.so), as their packages ship them; generated by',
    'scripts/rust-notices.mjs from the crates of THIRD_PARTY_NOTICES.md.',
    '',
  ];
  if (without.length > 0) {
    out.push('These packages ship no license file; their licenses are in the list:', ...without.map((name) => `  ${name}`), '');
  }
  const sorted = [...blocks.entries()].sort((a, b) => a[1][0].localeCompare(b[1][0], 'en'));
  for (const [text, users] of sorted) {
    out.push(`== ${users.join(', ')} ==`, '', text, '');
  }
  return out.join('\n');
}

/** Reads the SQLite version bundled by libsqlite3-sys from its sqlite3.h. */
function bundledSqlite(manifest) {
  const metadata = JSON.parse(cargo(['metadata', ...manifestArgs(manifest), '--locked', '--format-version', '1']));
  const sys = metadata.packages.find((pkg) => pkg.name === 'libsqlite3-sys');
  if (sys === undefined) {
    return null;
  }
  const header = readFileSync(join(dirname(sys.manifest_path), 'sqlite3', 'sqlite3.h'), 'utf8');
  const match = /^#define SQLITE_VERSION\s+"([^"]+)"/m.exec(header);
  if (match === null) {
    throw new Error('SQLITE_VERSION not found in the sqlite3.h bundled by libsqlite3-sys');
  }
  return { version: match[1], via: `libsqlite3-sys ${sys.version}` };
}

function rustTable(crates) {
  const rows = crates.map((c) => `| ${c.name} | ${c.version} | ${c.license} | <${c.source}> |`);
  return ['| Crate | Version | License | Source |', '|---|---|---|---|', ...rows].join('\n');
}

function sqliteRow(sqlite) {
  if (sqlite === null) {
    return '';
  }
  return `| SQLite (bundled by ${sqlite.via}) | ${sqlite.version} | Public domain | <https://sqlite.org/copyright.html> |`;
}

function replaceBetween(text, start, end, body, file = NOTICES_FILE) {
  const from = text.indexOf(start);
  const to = text.indexOf(end, from);
  if (from === -1 || to === -1 || to < from) {
    throw new Error(`markers ${start} ... ${end} not found in ${file}`);
  }
  // Blank lines around the table keep the HTML comments separate Markdown blocks.
  return `${text.slice(0, from + start.length)}\n\n${body}\n\n${text.slice(to)}`;
}

/** Replaces (or inserts) the SQLite row of the "Other" table. */
function replaceSqliteRow(text, row, file = NOTICES_FILE) {
  const lines = text.split('\n');
  const heading = lines.indexOf('## Other');
  if (heading === -1) {
    throw new Error(`section "## Other" not found in ${file}`);
  }
  const existing = lines.findIndex((line, index) => index > heading && line.startsWith(SQLITE_ROW_PREFIX));
  if (existing !== -1) {
    lines.splice(existing, 1, ...(row === '' ? [] : [row]));
    return lines.join('\n');
  }
  const separator = lines.findIndex((line, index) => index > heading && line.startsWith('|---'));
  if (separator === -1) {
    throw new Error(`the "## Other" table in ${file} has no header`);
  }
  if (row !== '') {
    lines.splice(separator + 1, 0, row);
  }
  return lines.join('\n');
}

function main() {
  const write = process.argv.includes('--write');
  const path = resolve(repoRoot, NOTICES_FILE);
  const current = readFileSync(path, 'utf8');

  const crates = collectCrates(ROOT_PACKAGE, DESKTOP_TARGETS);
  const android = collectCrates(ANDROID_PACKAGE, ANDROID_TARGETS);
  const sqlite = bundledSqlite();
  let expected = replaceBetween(current, RUST_START, RUST_END, rustTable(crates));
  expected = replaceBetween(expected, ANDROID_START, ANDROID_END, rustTable(android));
  expected = replaceSqliteRow(expected, sqliteRow(sqlite));
  const serverPath = resolve(repoRoot, SERVER_NOTICES_FILE);
  const serverCurrent = readFileSync(serverPath, 'utf8');
  const server = collectCrates(SERVER_PACKAGE, SERVER_TARGETS, SERVER_MANIFEST);
  const serverSqlite = bundledSqlite(SERVER_MANIFEST);
  let serverExpected = replaceBetween(serverCurrent, RUST_START, RUST_END, rustTable(server), SERVER_NOTICES_FILE);
  serverExpected = replaceSqliteRow(serverExpected, sqliteRow(serverSqlite), SERVER_NOTICES_FILE);
  const summary = `${crates.length} Rust crate(s) of the desktop, ${android.length} of the Android app, ${server.length} of the server${sqlite ? `, SQLite ${sqlite.version}` : ''}`;
  const licensesPath = resolve(repoRoot, ANDROID_LICENSES_FILE);
  const licenses = licenseTexts(android);
  let currentLicenses = '';
  try {
    currentLicenses = readFileSync(licensesPath, 'utf8');
  } catch {
    currentLicenses = '';
  }

  if (write) {
    if (expected !== current) {
      writeFileSync(path, expected);
    }
    if (serverExpected !== serverCurrent) {
      writeFileSync(serverPath, serverExpected);
    }
    if (licenses !== currentLicenses) {
      mkdirSync(dirname(licensesPath), { recursive: true });
      writeFileSync(licensesPath, licenses);
    }
    console.log(`${NOTICES_FILE}, ${SERVER_NOTICES_FILE}: ${summary} recorded; ${ANDROID_LICENSES_FILE} written.`);
    return;
  }

  if (licenses !== currentLicenses) {
    console.error(`${ANDROID_LICENSES_FILE} is out of date; run \`node scripts/rust-notices.mjs --write\`.`);
    process.exitCode = 1;
  }
  const staleNotices = reportStale(NOTICES_FILE, current, expected);
  const staleServer = reportStale(SERVER_NOTICES_FILE, serverCurrent, serverExpected);
  if (staleNotices || staleServer) {
    process.exitCode = 1;
    return;
  }
  console.log(`${NOTICES_FILE} and ${SERVER_NOTICES_FILE} are up to date: ${summary}.`);
}

/** Prints the lines `file` lacks and has too many against `expected`; true when it is stale. */
function reportStale(file, current, expected) {
  if (expected === current) {
    return false;
  }
  const have = new Set(current.split('\n'));
  const want = new Set(expected.split('\n'));
  console.error(`${file} is out of date; run \`node scripts/rust-notices.mjs --write\`.`);
  for (const line of want) {
    if (!have.has(line)) console.error(`  + ${line}`);
  }
  for (const line of have) {
    if (!want.has(line)) console.error(`  - ${line}`);
  }
  return true;
}

main();
