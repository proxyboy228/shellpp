//! Keychain key formats (stage 3; UI 7.1, 7.3; docs/data-model.md, section
//! 9.1): Generate key, and import of PEM PKCS#1, PKCS#8 (plain and
//! PBES2-encrypted), SEC1 and the legacy OpenSSL PEM encryption. Every key
//! is generated at run time and written in the source format by the crates
//! that define it (rsa, p256/p384/p521, ed25519-dalek, pkcs8); the expected
//! fingerprint comes from the same key converted directly by `ssh-key`.

