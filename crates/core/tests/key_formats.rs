fn import(
    core: &shellpp_core::Core,
    vault_id: Uuid,
    text: &str,
    pass: Option<&SecretString>,
    save: bool,
) -> Result<KeyImportResult, shellpp_core::CoreError> {
    core.key_import(KeyImportInput {
        vault_id,
        label: Some("imported".to_owned()),
        private_key: SecretString::from(text.to_owned()),
        passphrase: pass.cloned(),
        save_passphrase: save,
    })
}

/// A PEM block with 64-character lines and optional RFC 1421 headers.
fn pem(label: &str, der: &[u8], headers: &[(&str, String)]) -> String {
    let mut out = format!("-----BEGIN {label}-----\n");
    for (name, value) in headers {
        out.push_str(&format!("{name}: {value}\n"));
    }
    if !headers.is_empty() {
        out.push('\n');
    }
    let encoded = BASE64.encode(der);
    for chunk in encoded.as_bytes().chunks(64) {
        out.push_str(std::str::from_utf8(chunk).expect("ascii"));
        out.push('\n');
    }
    out.push_str(&format!("-----END {label}-----\n"));
    // Windows line endings, as files from Windows tools have them.
    out.replace('\n', "\r\n")
}

fn fingerprint_of(data: KeypairData) -> String {
    PrivateKey::new(data, "")
        .expect("key")
        .fingerprint(HashAlg::Sha256)
        .to_string()
}

fn random<const N: usize>() -> [u8; N] {
    let mut bytes = [0u8; N];
    getrandom::fill(&mut bytes).expect("os random");
    bytes
}

/// `EVP_BytesToKey(MD5, count 1)` as OpenSSL derives the legacy PEM key.
fn evp_bytes_to_key(pass: &[u8], salt: &[u8], len: usize) -> Vec<u8> {
    let mut out = Vec::new();
    let mut last: Vec<u8> = Vec::new();
    while out.len() < len {
        let mut input = last.clone();
        input.extend_from_slice(pass);
        input.extend_from_slice(salt);
        last = md5::compute(&input).0.to_vec();
        out.extend_from_slice(&last);
    }
    out.truncate(len);
    out
}

/// A DER body under the legacy OpenSSL PEM encryption.
fn legacy_pem(label: &str, der: &[u8], pass: &str, cipher: &str) -> String {
    let iv: [u8; 16] = random();
    let key_len = match cipher {
        "AES-128-CBC" => 16,
        "AES-192-CBC" => 24,
        "AES-256-CBC" => 32,
        other => panic!("cipher {other}"),
    };
    let key = evp_bytes_to_key(pass.as_bytes(), &iv[..8], key_len);
    let mut buffer = der.to_vec();
    buffer.resize(der.len() + 16, 0);
    let encrypted = match key_len {
        16 => cbc::Encryptor::<aes::Aes128>::new_from_slices(&key, &iv)
            .unwrap()
            .encrypt_padded::<Pkcs7>(&mut buffer, der.len())
            .unwrap()
            .to_vec(),
        24 => cbc::Encryptor::<aes::Aes192>::new_from_slices(&key, &iv)
            .unwrap()
            .encrypt_padded::<Pkcs7>(&mut buffer, der.len())
            .unwrap()
            .to_vec(),
        _ => cbc::Encryptor::<aes::Aes256>::new_from_slices(&key, &iv)
            .unwrap()
            .encrypt_padded::<Pkcs7>(&mut buffer, der.len())
            .unwrap()
            .to_vec(),
    };
    let iv_hex: String = iv.iter().map(|byte| format!("{byte:02X}")).collect();
    pem(
        label,
        &encrypted,
        &[
            ("Proc-Type", "4,ENCRYPTED".to_owned()),
            ("DEK-Info", format!("{cipher},{iv_hex}")),
        ],
    )
}

/// A key generated by the source crate: its PKCS#8 DER, its native DER
/// (PKCS#1 for RSA, SEC1 for EC; none for Ed25519) and its fingerprint.
struct Source {
    name: &'static str,
    pkcs8: Vec<u8>,
    native: Option<(&'static str, Vec<u8>)>,
    fingerprint: String,
    algorithm: &'static str,
}

/// A random EC secret key: random bytes of the curve size (the top byte
/// masked with `mask`) until they form a valid scalar.
fn ec_secret<K>(len: usize, mask: u8, make: impl Fn(&[u8]) -> Option<K>) -> K {
    loop {
        let mut bytes = vec![0u8; len];
        getrandom::fill(&mut bytes).expect("os random");
        bytes[0] &= mask;
        if let Some(key) = make(&bytes) {
            return key;
        }
    }
}

fn sources() -> Vec<Source> {
    use p256::pkcs8::EncodePrivateKey as _;
    let mut out = Vec::new();

    let seed: [u8; 32] = random();
    let signing = ed25519_dalek::SigningKey::from_bytes(&seed);
    out.push(Source {
        name: "ed25519",
        pkcs8: signing.to_pkcs8_der().expect("pkcs8").as_bytes().to_vec(),
        native: None,
        fingerprint: fingerprint_of(KeypairData::Ed25519(Ed25519Keypair::from_seed(&seed))),
        algorithm: "ssh-ed25519",
    });

    let secret = ec_secret(32, 0xff, |bytes| p256::SecretKey::from_slice(bytes).ok());
    out.push(Source {
        name: "p256",
        pkcs8: secret.to_pkcs8_der().expect("pkcs8").as_bytes().to_vec(),
        native: Some((
            "EC PRIVATE KEY",
            secret.to_sec1_der().expect("sec1").to_vec(),
        )),
        fingerprint: fingerprint_of(KeypairData::Ecdsa(EcdsaKeypair::NistP256 {
            public: secret.public_key().into(),
            private: secret.clone().into(),
        })),
        algorithm: "ecdsa-sha2-nistp256",
    });
    let secret = ec_secret(48, 0xff, |bytes| p384::SecretKey::from_slice(bytes).ok());
    out.push(Source {
        name: "p384",
        pkcs8: secret.to_pkcs8_der().expect("pkcs8").as_bytes().to_vec(),
        native: Some((
            "EC PRIVATE KEY",
            secret.to_sec1_der().expect("sec1").to_vec(),
        )),
        fingerprint: fingerprint_of(KeypairData::Ecdsa(EcdsaKeypair::NistP384 {
            public: secret.public_key().into(),
            private: secret.clone().into(),
        })),
        algorithm: "ecdsa-sha2-nistp384",
    });
    let secret = ec_secret(66, 0x01, |bytes| p521::SecretKey::from_slice(bytes).ok());
    out.push(Source {
        name: "p521",
        pkcs8: secret.to_pkcs8_der().expect("pkcs8").as_bytes().to_vec(),
        native: Some((
            "EC PRIVATE KEY",
            secret.to_sec1_der().expect("sec1").to_vec(),
        )),
        fingerprint: fingerprint_of(KeypairData::Ecdsa(EcdsaKeypair::NistP521 {
            public: secret.public_key().into(),
            private: secret.clone().into(),
        })),
        algorithm: "ecdsa-sha2-nistp521",
    });

    use rsa::pkcs1::EncodeRsaPrivateKey as _;
    let private = rsa::RsaPrivateKey::new(&mut OsRng, 2048).expect("rsa");
    out.push(Source {
        name: "rsa2048",
        pkcs8: private.to_pkcs8_der().expect("pkcs8").as_bytes().to_vec(),
        native: Some((
            "RSA PRIVATE KEY",
            private.to_pkcs1_der().expect("pkcs1").as_bytes().to_vec(),
        )),
        fingerprint: fingerprint_of(KeypairData::Rsa(
            RsaKeypair::try_from(private).expect("rsa keypair"),
        )),
        algorithm: "ssh-rsa",
    });
    out
}

#[test]
fn generated_keys_of_every_offered_kind() {
    let u = first_run();
    for kind in KeyKind::ALL {
        let label = format!("generated {kind:?}");
        let result = u
            .core
            .key_generate(KeyGenerateInput {
                vault_id: u.vault_id,
                label: label.clone(),
                kind,
                passphrase: None,
                save_passphrase: false,
            })
            .expect("generate");
        assert!(result.created, "{kind:?}");
        assert_eq!(result.key.algorithm, kind.algorithm_name());
        assert_eq!(result.key.label, label);
        assert!(!result.key.encrypted);
        assert!(result.key.fingerprint.is_some());
    }
    // Ed25519 is the default kind; RSA 2048 is not offered (D32).
    assert_eq!(KeyKind::default(), KeyKind::Ed25519);

    // With a passphrase: an encrypted OpenSSH key; saved on request.
    let pass = passphrase();
    let saved = u
        .core
        .key_generate(KeyGenerateInput {
            vault_id: u.vault_id,
            label: "with passphrase".to_owned(),
            kind: KeyKind::EcdsaP256,
            passphrase: Some(pass.clone()),
            save_passphrase: true,
        })
        .expect("generate encrypted");
    assert!(saved.key.encrypted);
    assert!(saved.key.passphrase_saved);
    let asked = u
        .core
        .key_generate(KeyGenerateInput {
            vault_id: u.vault_id,
            label: "ask every time".to_owned(),
            kind: KeyKind::Ed25519,
            passphrase: Some(pass),
            save_passphrase: false,
        })
        .expect("generate encrypted, not saved");
    assert!(asked.key.encrypted);
    assert!(!asked.key.passphrase_saved);

    // Two generated keys never collide.
    assert_ne!(saved.key.fingerprint, asked.key.fingerprint);

    // The label is required.
    let refused = u
        .core
        .key_generate(KeyGenerateInput {
            vault_id: u.vault_id,
            label: "  ".to_owned(),
            kind: KeyKind::Ed25519,
            passphrase: None,
            save_passphrase: false,
        })
        .unwrap_err();
    assert_eq!(
        reasons(refused),
        vec![("label".to_owned(), ValidationReason::Required)]
    );
}

#[test]
fn pem_pkcs8_pkcs1_and_sec1_keys_are_imported_as_openssh() {
    let u = first_run();
    for source in sources() {
        let text = pem("PRIVATE KEY", &source.pkcs8, &[]);
        assert_eq!(
            shellpp_core::keys::inspect(&text),
            Ok((Format::Pkcs8, false)),
            "{}",
            source.name
        );
        let result = import(&u.core, u.vault_id, &text, None, false).expect(source.name);
        assert!(result.created, "{}", source.name);
        assert_eq!(result.key.algorithm, source.algorithm, "{}", source.name);
        assert_eq!(
            result.key.fingerprint.as_deref(),
            Some(source.fingerprint.as_str()),
            "{}",
            source.name
        );
        assert!(!result.key.encrypted);
        // The same key in its native format is the same record.
        if let Some((label, der)) = &source.native {
            let text = pem(label, der, &[]);
            let again = import(&u.core, u.vault_id, &text, None, false).expect(source.name);
            assert!(!again.created, "{} {label}", source.name);
            assert_eq!(again.key.record_id, result.key.record_id);
        }
    }
}

#[test]
fn encrypted_pem_keys_are_stored_encrypted_with_the_same_passphrase() {
    let u = first_run();
    let pass = passphrase();
    let sources = sources();
    let rsa = sources
        .iter()
        .find(|source| source.name == "rsa2048")
        .unwrap();
    let p256 = sources.iter().find(|source| source.name == "p256").unwrap();

    // Legacy OpenSSL encryption of PKCS#1 and SEC1 with each AES size.
    let cases = [
        (rsa, "AES-128-CBC"),
        (p256, "AES-192-CBC"),
        (p256, "AES-256-CBC"),
    ];
    for (index, (source, cipher)) in cases.into_iter().enumerate() {
        let (label, der) = source.native.as_ref().unwrap();
        let text = legacy_pem(label, der, pass.expose_secret(), cipher);
        let format = if *label == "RSA PRIVATE KEY" {
            Format::Pkcs1
        } else {
            Format::Sec1
        };
        assert_eq!(shellpp_core::keys::inspect(&text), Ok((format, true)));
        // Without a passphrase, and with a wrong one.
        assert_eq!(
            reasons(import(&u.core, u.vault_id, &text, None, false).unwrap_err()),
            vec![("passphrase".to_owned(), ValidationReason::Required)],
            "{cipher}"
        );
        let wrong = SecretString::from("not the passphrase".to_owned());
        assert_eq!(
            reasons(import(&u.core, u.vault_id, &text, Some(&wrong), false).unwrap_err()),
            vec![("passphrase".to_owned(), ValidationReason::Invalid)],
            "{cipher}"
        );
        // Saved on the first case, asked on every connection on the others.
        let save = index == 0;
        let result = import(&u.core, u.vault_id, &text, Some(&pass), save).expect(cipher);
        assert_eq!(
            result.key.fingerprint.as_deref(),
            Some(source.fingerprint.as_str()),
            "{cipher}"
        );
        assert!(result.key.encrypted, "stored encrypted: {cipher}");
        assert_eq!(result.key.passphrase_saved, save, "{cipher}");
    }

    // PBES2-encrypted PKCS#8 with PBKDF2 and with scrypt.
    let ed25519 = sources
        .iter()
        .find(|source| source.name == "ed25519")
        .unwrap();
    let info = pkcs8::PrivateKeyInfoRef::try_from(ed25519.pkcs8.as_slice()).unwrap();
    let salt: [u8; 16] = random();
    let iv: [u8; 16] = random();
    let pbkdf2 =
        pkcs8::pkcs5::pbes2::Parameters::generate_pbkdf2_sha256_aes256cbc(2048, &salt, iv).unwrap();
    let encrypted = [
        info.encrypt_with_params(pbkdf2, pass.expose_secret().as_bytes())
            .unwrap(),
        info.encrypt_with_rng(&mut OsRng, pass.expose_secret().as_bytes())
            .unwrap(),
    ];
    for document in encrypted {
        let text = pem("ENCRYPTED PRIVATE KEY", document.as_bytes(), &[]);
        assert_eq!(
            shellpp_core::keys::inspect(&text),
            Ok((Format::Pkcs8, true))
        );
        let wrong = SecretString::from("wrong".to_owned());
        assert_eq!(
            reasons(import(&u.core, u.vault_id, &text, Some(&wrong), false).unwrap_err()),
            vec![("passphrase".to_owned(), ValidationReason::Invalid)]
        );
        let result = import(&u.core, u.vault_id, &text, Some(&pass), false).expect("pkcs8");
        assert_eq!(
            result.key.fingerprint.as_deref(),
            Some(ed25519.fingerprint.as_str())
        );
        assert!(result.key.encrypted);
    }
}

#[test]
fn unusable_texts_say_why() {
    let u = first_run();
    let inspect = shellpp_core::keys::inspect;
    // A public key instead of the private one: a `.pub` line (also with
    // authorized_keys options), an RFC 4716 block, a PEM public key.
    let key = stage2::generate(stage2::KeyKind::Ed25519, "");
    let public = key.public_key().to_openssh().unwrap();
    assert_eq!(inspect(&public), Err(KeyProblem::PublicKey));
    assert_eq!(
        inspect(&format!("no-pty,restrict {public}")),
        Err(KeyProblem::PublicKey)
    );
    assert_eq!(
        inspect(&format!("command=\"echo hi there\",no-pty {public}")),
        Err(KeyProblem::PublicKey)
    );
    assert_eq!(
        inspect(
            "---- BEGIN SSH2 PUBLIC KEY ----\nAAAAC3NzaC1lZDI1NTE5\n---- END SSH2 PUBLIC KEY ----\n"
        ),
        Err(KeyProblem::PublicKey)
    );
    assert_eq!(
        inspect(&pem("PUBLIC KEY", &[0x30, 0x03, 0x02, 0x01, 0x00], &[])),
        Err(KeyProblem::PublicKey)
    );
    // Not a key at all: a certificate block, text, a word that looks like
    // an algorithm.
    assert_eq!(inspect("ssh-ed25519 not-base64"), Err(KeyProblem::NotAKey));
    assert_eq!(
        inspect(&pem("CERTIFICATE", &[1, 2, 3], &[])),
        Err(KeyProblem::NotAKey)
    );
    assert_eq!(inspect("hello"), Err(KeyProblem::NotAKey));
    // A damaged body.
    assert_eq!(
        inspect(&pem("PRIVATE KEY", &[0x30, 0x03, 0x02, 0x01], &[])),
        Err(KeyProblem::Damaged)
    );
    // X25519 is not a signing key.
    let mut x25519 = vec![
        0x30, 0x2e, 0x02, 0x01, 0x00, 0x30, 0x05, 0x06, 0x03, 0x2b, 0x65, 0x6e, 0x04, 0x22, 0x04,
        0x20,
    ];
    x25519.extend_from_slice(&random::<32>());
    assert!(matches!(
        inspect(&pem("PRIVATE KEY", &x25519, &[])),
        Err(KeyProblem::Algorithm(_))
    ));
    // RSA under 2048 bits.
    use rsa::pkcs1::EncodeRsaPrivateKey as _;
    let small = rsa::RsaPrivateKey::new(&mut OsRng, 1024).expect("rsa 1024");
    let text = pem(
        "RSA PRIVATE KEY",
        small.to_pkcs1_der().unwrap().as_bytes(),
        &[],
    );
    assert_eq!(inspect(&text), Err(KeyProblem::RsaTooSmall));
    assert_eq!(
        reasons(import(&u.core, u.vault_id, &text, None, false).unwrap_err()),
        vec![("private_key".to_owned(), ValidationReason::NotAllowed)]
    );
    // A legacy encryption this app does not read.
    let text = pem(
        "RSA PRIVATE KEY",
        &[0u8; 32],
        &[
            ("Proc-Type", "4,ENCRYPTED".to_owned()),
            ("DEK-Info", "DES-EDE3-CBC,0102030405060708".to_owned()),
        ],
    );
    let pass = passphrase();
    assert_eq!(
        reasons(import(&u.core, u.vault_id, &text, Some(&pass), false).unwrap_err()),
        vec![("private_key".to_owned(), ValidationReason::NotAllowed)]
    );
}
